#include <stdio.h>

int main() {
    double I, R, t, Q;

    printf("=== Розрахунок теплової енергії Джоуля-Ленца (Варіант 14) ===\n\n"); //[cite: 1]

    // 1. Введення та перевірка струму I (А)[cite: 1]
    printf("Введіть значення струму I (в амперах, А): ");
    if (scanf("%lf", &I) != 1) {
        printf("Помилка: введено не числове значення для струму!\n");
        return 1;
    }

    // 2. Введення та перевірка опору R (Ом)[cite: 1]
    printf("Введіть значення опору R (в омах, Ом): ");
    if (scanf("%lf", &R) != 1) {
        printf("Помилка: введено не числове значення для опору!\n");
        return 1;
    }
    // Запобігання некоректним значенням (опір не може бути від'ємним)
    if (R < 0) {
        printf("Помилка: опір не може бути від'ємним!\n");
        return 1;
    }

    // 3. Введення та перевірка часу t (с)[cite: 1]
    printf("Введіть значення часу t (в секундах, с): ");
    if (scanf("%lf", &t) != 1) {
        printf("Помилка: введено не числове значення для часу!\n");
        return 1;
    }
    // Запобігання некоректним значенням (час не може бути від'ємним)
    if (t < 0) {
        printf("Помилка: час не може бути від'ємним!\n");
        return 1;
    }

    // 4. Обчислення за формулою варіанта 14: Q = I^2 * R * t[cite: 1]
    Q = (I * I) * R * t;

    // 5. Виведення результату з точністю до 2 знаків після коми та вказівкою одиниць вимірювання (Дж)[cite: 1]
    printf("\n----------------------------------------\n");
    printf("Теплова енергія Q = %.2f Дж\n", Q); //[cite: 1]
    printf("----------------------------------------\n");

    return 0;
}